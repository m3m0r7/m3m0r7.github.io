import { FILE_TREE, fileDocument } from './documents.mjs';
import { documentText } from './document-format.mjs';
import { hasLink } from './state.mjs';
const HOME='/home/memory';
const directories=new Map([['/',['home','etc','var']],['/home',['memory']],['/etc',['hostname','resolv.conf']],['/var',['log']],['/var/log',['syslog']]]),files=new Map();
function populate(name,path){const folder=FILE_TREE[name];directories.set(path,[...folder.folders,...folder.files]);for(const child of folder.folders)populate(child,`${path}/${child}`);for(const name of folder.files)files.set(`${path}/${name}`,fileDocument(name));}
populate('ホーム',HOME);
function resolve(value,cwd){const source=value==='~'?HOME:value.startsWith('~/')?HOME+value.slice(1):value.startsWith('/')?value:cwd+'/'+value,parts=[];for(const part of source.split('/')){if(!part||part==='.')continue;if(part==='..')parts.pop();else parts.push(part)}return '/'+parts.join('/');}
const tokenize=text=>text.match(/"[^"]*"|'[^']*'|[^\s]+/g)?.map(token=>/^["']/.test(token)?token.slice(1,-1):token)||[];
const MANUALS={
  lst:'lst [-la] [path]\nディレクトリの内容を表示する。',
  crt:'crt\n現在のディレクトリを表示する。',
  chgdir:'chgdir [path]\n作業ディレクトリを移動する。引数を省くとホームへ戻る。',
  read:'read path...\nファイルの内容を表示する。長い文書は端末内をスクロールして読む。',
  head:'head [-n N] path\n先頭 N 行を表示する。',
  grep:'grep [-i] pattern path\n一致する行を表示する。',
  find:'find [path] [-name pattern]\n指定した場所以下のファイルとフォルダを探す。',
  icfg:'icfg [eth0|-a]\nmemoryOS のインターフェース状態、アドレスとキャリアを表示する。',
  irt:'irt\n経路表を表示する。',
  p:'p [-c N] host\n宛先への疎通を確認する。',
  nlp:'nlp host\nDNS の名前解決結果を表示する。',
};
export function executeFileCommand(input,state,session={}){
  const args=tokenize(input.trim()),verb=args.shift()?.toLowerCase(),cwd=directories.has(session.cwd)?session.cwd:HOME;
  function read(path){
    if(path==='/etc/hostname')return {text:'memory-home'};
    if(path==='/etc/resolv.conf')return {text:hasLink(state)&&state.autoIP&&state.autoDNS?'# Generated by memoryOS NetworkService\nnameserver 192.168.10.1':'# No nameservers configured'};
    if(path==='/var/log/syslog')return {text:`kernel: eth0: NIC Link is ${hasLink(state)?'Up 1000 Mbps Full Duplex':'Down'}\nmemoryOS NetworkService: ${hasLink(state)&&state.autoIP?'DHCP lease 192.168.10.24':'waiting for carrier'}`};
    const doc=files.get(path);if(doc)return {text:documentText(doc,state.taskChecks),clue:doc.clue};
    return {error:directories.has(path)?'ディレクトリです':'そのファイルはありません'};
  }
  if(verb==='crt')return {output:cwd};
  if(verb==='chgdir'){const target=resolve(args[0]||'~',cwd);return directories.has(target)?{output:'',cwd:target}:{output:`chgdir: ${args[0]}: ディレクトリが見つかりません`};}
  if(verb==='lst'){
    const target=resolve(args.find(arg=>!arg.startsWith('-'))||'.',cwd),entries=directories.get(target),long=args.some(arg=>arg.startsWith('-')&&arg.includes('l')),all=args.some(arg=>arg.startsWith('-')&&arg.includes('a'));
    if(!entries)return files.has(target)?{output:target.split('/').at(-1)}:{output:`lst: ${target}: そのファイルはありません`};
    return {output:(all?['.','..',...entries]:entries).map(name=>long?`${directories.has(resolve(name,target))?'drwxr-xr-x':'-rw-r--r--'}  memory  ${name}`:name).join(long?'\n':'  ')};
  }
  if(['read','more','head'].includes(verb)){
    let count=10;const n=args.indexOf('-n');if(n>=0){count=Number(args[n+1]);args.splice(n,2);if(!Number.isSafeInteger(count)||count<0||count>10000)return {output:`${verb}: 行数を 0〜10000 で指定してください`};}
    if(!args.length)return {output:`${verb}: ファイル名を指定してください`};
    let clue;const output=args.map(arg=>{const doc=read(resolve(arg,cwd));if(doc.error)return `${verb}: ${arg}: ${doc.error}`;clue ||=doc.clue;const lines=doc.text.split('\n');return verb==='head'?lines.slice(0,count).join('\n'):doc.text}).join('\n');return {output,clue};
  }
  if(verb==='grep'){
    const insensitive=args[0]==='-i';if(insensitive)args.shift();const pattern=args.shift(),name=args.shift();if(pattern===undefined||!name)return {output:'grep: 検索語とファイル名を指定してください'};const doc=read(resolve(name,cwd));if(doc.error)return {output:`grep: ${name}: ${doc.error}`};const fold=text=>insensitive?text.toLocaleLowerCase():text;return {output:doc.text.split('\n').filter(line=>fold(line).includes(fold(pattern))).join('\n'),clue:doc.clue};
  }
  if(verb==='find'){
    const target=resolve(args[0]&&!args[0].startsWith('-')?args.shift():'.',cwd);if(!directories.has(target))return {output:`find: ${target}: ディレクトリが見つかりません`};const n=args.indexOf('-name'),pattern=n<0?'*':args[n+1]||'*';const escaped=pattern.replace(/[.+?^${}()|[\]\\]/g,'\\$&').replace(/\*/g,'.*'),matches=new RegExp('^'+escaped+'$');return {output:[...directories.keys(),...files.keys()].filter(path=>(path===target||path.startsWith(target==='/'?'/':target+'/'))&&matches.test(path.split('/').at(-1))).join('\n')};
  }
  if(verb==='whoami')return {output:'memory'};
  if(verb==='uname')return {output:args.includes('-a')?'memoryOS memory-home 1.0 x86_64':'memoryOS'};
  if(verb==='date')return {output:new Date().toLocaleString('ja-JP')};
  if(verb==='echo')return {output:args.map(arg=>arg==='$HOME'?HOME:arg==='$PWD'?cwd:arg).join(' ')};
  if(verb==='man')return {output:MANUALS[args[0]]||`man: ${args[0]||''}: マニュアルが見つかりません`};
  if(verb==='history')return {output:(session.history||[]).map((line,i)=>`${String(i+1).padStart(4)}  ${line}`).join('\n')};
  return null;
}
